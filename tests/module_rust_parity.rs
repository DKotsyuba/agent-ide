/// The resident memory of `id` in KiB, 0 once it is gone.
fn rss_kib(id: ProcessIdentity) -> u64 {
    let listing = std::process::Command::new("/bin/ps")
        .args(["-o", "rss=", "-p", &id.pid.to_string()])
        .output()
        .unwrap();
    String::from_utf8_lossy(&listing.stdout)
        .trim()
        .parse()
        .unwrap_or(0)
}

