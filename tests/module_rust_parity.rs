/// The Rust analyzer module shares the supervised slots' restart policy: after the initial
/// start and three restarts within the window (each death settled typed on the next demand),
/// a further demand is refused `restart_exhausted` (typed, on the same daemon) and no fifth
/// module starts.
#[tokio::test]
#[ignore = "requires the accepted AGENT_IDE_RUST_TOOLCHAIN_DIR, AGENT_IDE_RUST_ANALYZER and AGENT_IDE_RUST_TOOLCHAIN inputs"]
async fn rust_analyzer_crash_loop_exhausts_the_restart_budget() {
    let fixture = rust_fixture(PARITY_FILES, "module-rust-crash-loop", 300);
    let mut daemon = Daemon::start(&fixture, &[MODULE]).await;
    let daemon_pid = daemon.pid();
    let mut session = Session::start(&fixture).await;
    let outline = json!({"path":"src/lib.rs"});
    let context = json!({"path":"src/lib.rs","byte_offset":WORK_OFFSET});
    // Deaths are noticed through the backend's own path (context) and through the core's
    // semantic paths (symbol, graph); each counts once against the same budget.
    let demands = [
        ("ide.context", context.clone()),
        ("ide.symbol", json!({"symbol":"src/lib.rs#Service/work"})),
        ("ide.graph", json!({"symbol":"src/lib.rs#user"})),
        ("ide.symbol", json!({"symbol":"src/lib.rs#user"})),
    ];
    for attempt in 0..4 {
        // A demand starts the module (the first after a death is settled with its fault).
        let (tool, arguments) = &demands[attempt];
        let deadline = Instant::now() + Duration::from_secs(30);
        let module = loop {
            let _ = session.call(&fixture, tool, arguments.clone()).await;
            if let Some((module, _)) = analyzer(&daemon.tree()) {
                break module;
            }
            assert!(
                Instant::now() < deadline,
                "attempt {attempt}: no analyzer module"
            );
        };
        // SAFETY: the exact module identity captured as a child of this test's daemon.
        unsafe { libc::kill(module.id.pid, libc::SIGKILL) };
        assert!(module.id.gone().await);
        // Let each backoff (250 ms, 1 s, 4 s) pass so the next start really happens.
        tokio::time::sleep(Duration::from_millis([300, 1100, 4100, 0][attempt])).await;
    }
    // The symbol card names a module's typed failure (context answers lexically instead).
    let usages = json!({"symbol":"src/lib.rs#Service/work"});
    let mut refused = Value::Null;
    for _ in 0..3 {
        refused = session.call(&fixture, "ide.symbol", usages.clone()).await;
        if refused.to_string().contains("restart_exhausted") {
            break;
        }
    }
    assert!(
        refused.to_string().contains("restart_exhausted"),
        "a demand names the exhausted budget: {refused}"
    );
    assert!(
        analyzer(&daemon.tree()).is_none(),
        "no fifth module started"
    );
    let lexical = session.call(&fixture, "ide.outline", outline).await;
    assert_eq!(
        lexical["kind"], "outline",
        "outline still answers from source: {lexical}"
    );
    assert_eq!(daemon.pid(), daemon_pid, "same daemon");
    session.close(&fixture).await;
}

/// `text` with each opaque reference a reply names in prose (`source_ref <64 hex>-<n>`, also
/// `detail_ref …`, whatever punctuation follows) written as `<ref>`; other hex runs stay.
fn mask_text_refs(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    loop {
        let next = ["source_ref ", "detail_ref "]
            .iter()
            .filter_map(|marker| rest.find(marker).map(|at| (at, marker.len())))
            .min();
        let Some((at, marker)) = next else {
            out.push_str(rest);
            return out;
        };
        out.push_str(&rest[..at + marker]);
        rest = &rest[at + marker..];
        let hex = rest.bytes().take_while(u8::is_ascii_hexdigit).count();
        if hex == 64 {
            let suffix = rest[hex..].strip_prefix('-').map_or(0, |tail| {
                1 + tail.bytes().take_while(u8::is_ascii_digit).count()
            });
            out.push_str("<ref>");
            rest = &rest[hex + suffix..];
        }
    }
}

/// `text` with the per-daemon observation counters of a context reply masked (`source_sequence:`
/// and `document_version:`): they count every observation of the run, and the readiness wait
/// polls a variable number of times. Everything else stays byte-compared.
fn mask_counters(text: &str) -> String {
    text.split('\n')
        .map(|line| {
            if line.starts_with("source_sequence: ") {
                "source_sequence: <n>".to_owned()
            } else if line.starts_with("document_version: Some(") {
                "document_version: Some(<n>)".to_owned()
            } else {
                line.to_owned()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Only the elapsed slot of test result lines is masked; budgets and other text stay.
#[test]
fn seconds_are_masked_and_nothing_else() {
    assert_eq!(
        mask_seconds("tests #2: 1 passed, 1 failed, 3 s\ntests #3: no summary parsed, 12 s"),
        "tests #2: 1 passed, 1 failed, <seconds> s\ntests #3: no summary parsed, <seconds> s"
    );
    for kept in [
        "tests #1: started — cargo test --lib (budget 120 s); poll: call ide.test",
        "tests #1: stopped at budget 120 s — 1 passed, 0 failed so far",
        "a line, 3 s that is not a test result",
    ] {
        assert_eq!(mask_seconds(kept), kept);
    }
    assert_ne!(
        mask_seconds("tests #1: started — cargo test (budget 120 s)"),
        mask_seconds("tests #1: started — cargo test (budget 60 s)"),
        "two budgets stay different"
    );
}

