/// Opaque references are masked wherever a structured reply carries them; nulls and other
/// values (hashes in business fields included) stay.
#[test]
fn references_are_masked_and_nothing_else() {
    let mut reply = json!({"result":{"source_ref":"a".repeat(64) + "-2","outcome":"replaced",
        "digest":"b".repeat(64)},"detail_ref":null,"items":[{"detail_ref":"c-1"}]});
    mask_refs(&mut reply);
    let mut arguments = json!({"op":"replace","source_ref":"d".repeat(64) + "-7","lines":"2-2"});
    mask_refs(&mut arguments);
    assert_eq!(
        arguments,
        json!({"op":"replace","source_ref":"<ref>","lines":"2-2"})
    );
    assert_eq!(
        reply,
        json!({"result":{"source_ref":"<ref>","outcome":"replaced","digest":"b".repeat(64)},
            "detail_ref":null,"items":[{"detail_ref":"<ref>"}]})
    );
}

/// The daemon's own open path for a Rust analyzer module, without the daemon: the pinned
/// shipping binary started by `analyzer_command` (the module environment the root declares),
/// `analyzer_offer` with the backend's grant and settings, `open_session` with the static Rust
/// session shape, then the session's readiness barrier across the boundary until ready.
#[tokio::test]
#[ignore = "requires the accepted AGENT_IDE_RUST_TOOLCHAIN_DIR, AGENT_IDE_RUST_ANALYZER and AGENT_IDE_RUST_TOOLCHAIN inputs"]
async fn the_daemon_open_path_reaches_a_ready_rust_analyzer() {
    use agent_ide_core::{
        intelligence::{freshness::ViewGeneration, session::ProviderSettings},
        modules::{analyzer, launch::ModuleExecutable},
        workspace::authority::WorktreeRef,
    };
    agent_ide::languages::install();
    let fixture = Fixture::new(PARITY_FILES, providers("module-rust-open"));
    let dir = std::path::PathBuf::from(input("AGENT_IDE_RUST_TOOLCHAIN_DIR"));
    let namespace = fixture.base.join("namespace");
    for sub in ["cargo", "target", "tmp"] {
        std::fs::create_dir_all(namespace.join(sub)).unwrap();
    }
    let settings = agent_ide_lang_rust::module::RustProviderSettings {
        binary: input("AGENT_IDE_RUST_ANALYZER").into(),
        version: "rust-analyzer 1.98.1 (48a229ce 2026-09-01)".into(),
        cargo: dir.join("bin/cargo"),
        cargo_home: None,
        cargo_version: "cargo 1.98.1".into(),
        rustc: dir.join("bin/rustc"),
        rustc_version: "rustc 1.98.1".into(),
        toolchain: input("AGENT_IDE_RUST_TOOLCHAIN"),
        trust: "fixture-disabled".into(),
        cache_namespace: namespace.display().to_string(),
    };
    let digest = |path: &std::path::Path| {
        blake3::hash(&std::fs::read(path).unwrap())
            .to_hex()
            .to_string()
    };
    let executable = ModuleExecutable::pin(&parity::binary()).expect("a pinned module binary");
    let worktree = WorktreeRef::from_discovery(
        fixture.root.clone(),
        fixture.root.clone(),
        fixture.root.join(".git"),
        1,
    )
    .unwrap();
    let command = analyzer::analyzer_command(&executable, "rust", &worktree).expect("a command");
    let mut child = agent_ide_core::execution::spawn_granted_provider(&command).unwrap();
    let offer = analyzer::analyzer_offer(
        &executable,
        "rust",
        1,
        &worktree,
        [&settings.binary, &settings.cargo, &settings.rustc]
            .into_iter()
            .map(|path| (path.clone(), digest(path)))
            .collect(),
        [namespace.clone()]
            .into_iter()
            .chain(agent_ide_core::userhome::user_home())
            .chain(["/usr/bin", "/bin"].map(std::path::PathBuf::from))
            .collect(),
        Duration::from_secs(30),
        serde_json::to_value(&settings).unwrap(),
    );
    let generation = ViewGeneration {
        backend: 1,
        configuration: 1,
        toolchain: 1,
        view: 1,
    };
    let started = Instant::now();
    let mut live = analyzer::open_session(
        child.stdout.take().unwrap(),
        child.stdin.take().unwrap(),
        offer,
        worktree,
        1,
        generation,
        ProviderSettings::new(agent_ide_lang_rust::profile::RustModuleSession),
        Duration::from_secs(30),
    )
    .await
    .unwrap_or_else(|error| panic!("open: {error}"));
    eprintln!("open after {:?}", started.elapsed());
    let deadline = Instant::now() + Duration::from_secs(120);
    loop {
        match live.wait_ready(Duration::from_millis(100)).await {
            Ok(()) => break,
            Err(error) => {
                // A warming provider is loading, never a gone transport.
                assert!(
                    !matches!(
                        error,
                        agent_ide_core::intelligence::session::ReadinessError::Gone
                    ),
                    "a live module answered its readiness as gone: alive {} fault {:?}",
                    live.is_alive(),
                    live.module_unavailable()
                );
                assert!(
                    Instant::now() < deadline,
                    "never ready: {error:?}; fault {:?}",
                    live.module_unavailable()
                );
                eprintln!(
                    "readiness after {:?}: {error:?} alive {} fault {:?} remote {:?}",
                    started.elapsed(),
                    live.is_alive(),
                    live.module_unavailable(),
                    live.remote_fault()
                );
                tokio::time::sleep(Duration::from_millis(300)).await;
            }
        }
    }
    eprintln!("ready after {:?}", started.elapsed());
    let _ = child.kill().await;
}

/// A language server that completes the handshake as the accepted rust-analyzer, reports itself
/// quiescent and fails every documentSymbols and references request (copied from the product
/// suite's in-process control).
const EXCHANGE_STUB_SERVER: &str = r#"
const send = (message) => {
  const text = JSON.stringify(message);
  process.stdout.write(`Content-Length: ${Buffer.byteLength(text)}\r\n\r\n${text}`);
};
const reply = (id, result) => send({ jsonrpc: '2.0', id, result });
const fail = (id) => send({ jsonrpc: '2.0', id, error: { code: -32603, message: 'fixture exchange failure' } });
let buffer = Buffer.alloc(0);
process.stdin.on('data', (chunk) => {
  buffer = Buffer.concat([buffer, chunk]);
  for (;;) {
    const header = buffer.indexOf('\r\n\r\n');
    if (header < 0) return;
    const length = parseInt(buffer.slice(0, header).toString().match(/Content-Length: (\d+)/)?.[1] ?? '0', 10);
    if (buffer.length < header + 4 + length) return;
    const message = JSON.parse(buffer.slice(header + 4, header + 4 + length).toString());
    buffer = buffer.slice(header + 4 + length);
    switch (message.method) {
      case 'initialize':
        reply(message.id, {
          capabilities: {
            textDocumentSync: 1,
            documentSymbolProvider: true,
            hoverProvider: true,
            referencesProvider: true,
          },
          serverInfo: { name: 'rust-analyzer', version: '1.98.1 (48a229ce 2026-09-01)' },
        });
        break;
      case 'shutdown':
        reply(message.id, null);
        break;
      case 'exit':
        process.exit(0);
      case 'textDocument/documentSymbol':
      case 'textDocument/references':
        fail(message.id);
        break;
      default:
        if (message.id !== undefined) reply(message.id, null);
    }
  }
});
const report = () => {
  send({ jsonrpc: '2.0', method: 'experimental/serverStatus', params: { health: 'ok', quiescent: true } });
  setTimeout(report, 100);
};
report();
"#;

/// The module-mode twin of the in-process `configured_product_failed_exchange_rust_outline_
/// answers_from_source` (pinned in process): a provider that is ready but fails documentSymbols
/// and references. The outline and a symbol read answer from the exact source outline with the
/// module's typed cause in the footer, a file the source scanner refuses keeps its refusal, and
/// the symbol card's live sections name the typed `rust: module_unavailable (bundled.rust:…)`.
#[tokio::test]
#[ignore = "requires the accepted AGENT_IDE_NODE and AGENT_IDE_RUST_TOOLCHAIN_DIR inputs"]
async fn a_failed_provider_exchange_answers_from_source_with_typed_attribution() {
    use std::os::unix::fs::PermissionsExt;
    let base = std::env::temp_dir()
        .canonicalize()
        .unwrap()
        .join(format!("exchange-stub-{}", std::process::id()));
    std::fs::create_dir_all(&base).unwrap();
    let stub = base.join("exchange-stub-server.mjs");
    std::fs::write(&stub, EXCHANGE_STUB_SERVER).unwrap();
    let wrapper = base.join("exchange-rust-provider");
    std::fs::write(
        &wrapper,
        format!(
            "#!/bin/sh\nexec '{}' '{}'\n",
            input("AGENT_IDE_NODE"),
            stub.display()
        ),
    )
    .unwrap();
    std::fs::set_permissions(&wrapper, std::fs::Permissions::from_mode(0o700)).unwrap();
    let dir = input("AGENT_IDE_RUST_TOOLCHAIN_DIR");
    let fixture = Fixture::new(
        &[
            (
                "Cargo.toml",
                "[package]\nname = \"exchange\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
            ),
            (
                "src/lib.rs",
                "/// Answers broken.\npub fn value() -> i32 { 7 }\n\npub fn caller() -> i32 { value() }\n",
            ),
            (
                "src/refused.rs",
                "// attached to the item below\npub fn refused() {}\n",
            ),
        ],
        json!([{
            "executable":accepted(wrapper.to_str().unwrap(),"rust-analyzer 1.98.1 (48a229ce 2026-09-01)"),
            "settings":"rust_cache_priming_disabled_v1",
            "toolchain":"1.98.1-aarch64-apple-darwin",
            "cargo":accepted(&format!("{dir}/bin/cargo"),"cargo 1.98.1"),
            "cargo_version":"cargo 1.98.1",
            "rustc":accepted(&format!("{dir}/bin/rustc"),"rustc 1.98.1"),
            "rustc_version":"rustc 1.98.1",
            "trust":"fixture-disabled",
            "cache_namespace":"module-rust-exchange"
        }]),
    );
    let daemon = Daemon::start(&fixture, &[MODULE]).await;
    let mut session = Session::start(&fixture).await;
    let deadline = Instant::now() + Duration::from_secs(60);
    let outline = loop {
        let reply = session
            .call(&fixture, "ide.outline", json!({"path":"src/lib.rs"}))
            .await;
        if reply["kind"] == "outline"
            && !reply["text"]
                .as_str()
                .unwrap_or_default()
                .contains("still indexing")
        {
            break reply;
        }
        assert!(
            Instant::now() < deadline,
            "the outline never settled: {reply}"
        );
        tokio::time::sleep(Duration::from_millis(250)).await;
    };
    let text = outline["text"].as_str().unwrap_or_default();
    assert!(text.contains("pub fn value() -> i32"), "{outline}");
    assert!(
        text.contains("outline: from source, exact (")
            && text.contains("module_unavailable (bundled.rust:"),
        "the exchange-failed outline answers from source with the typed cause: {outline}"
    );
    let read = session
        .call(&fixture, "ide.read", json!({"symbol":"src/lib.rs#value"}))
        .await;
    let read_text = read["text"].as_str().unwrap_or_default();
    assert!(read_text.contains("pub fn value()"), "{read}");
    assert!(
        read_text.contains("outline: from source, exact ("),
        "{read}"
    );
    let refused = session
        .call(&fixture, "ide.outline", json!({"path":"src/refused.rs"}))
        .await;
    assert_eq!(refused["code"], "provider_unavailable", "{refused}");
    let symbol = session
        .call(&fixture, "ide.symbol", json!({"symbol":"src/lib.rs#value"}))
        .await;
    let card = symbol["text"].as_str().unwrap_or_default();
    assert_eq!(symbol["kind"], "symbol", "{symbol}");
    assert!(
        card.contains("signature: pub fn value() -> i32"),
        "{symbol}"
    );
    assert!(
        card.contains("usages: unavailable (rust: module_unavailable (bundled.rust:"),
        "the card's live sections name the typed module fault: {symbol}"
    );
    session.close(&fixture).await;
    drop(daemon);
    let _ = std::fs::remove_dir_all(&base);
}

